#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
=======================================================================================================================
 cad_to_twin.py - turns the CAD builder's export (cad/<asm>/parts.json) into the twin's link mass properties, so no
                  mass, CoM or inertia is ever typed by hand.

 Interpreter: any Python >= 3.9 (stdlib only). Run:
     python -I sim/twin/tools/cad_to_twin.py --parts cad/<asm>/parts.json --link <part> [<part> ...]
            --axis-mm X Y Z --axis-dir X Y Z --out sim/twin/out/link_mass.txt
     python -I sim/twin/tools/cad_to_twin.py --self-test
 Paths: command line

 Input schema (what cad/ builders export; templates/cad/mass_cg_table.py reads the same file):
     {"parts": {"<name>": {"mass_g": 31.2, "com_mm": [x, y, z],
                           "inertia_kgmm2": [[Ixx, Ixy, Ixz], [Ixy, Iyy, Iyz], [Ixz, Iyz, Izz]]   (optional, about the
                           part's own CoM, CAD axes)}}}
 Output (params include file, SI): joint.m_link_kg, joint.l_com_m (perpendicular distance of the link CoM from the
 axis) and joint.j_link_kgm2 (inertia of the moving parts about the axis: each part's own inertia projected on the
 axis plus m d^2, the parallel-axis theorem). A part without inertia_kgmm2 counts as a point mass and is listed in a
 warning comment in the output, because a point mass UNDERESTIMATES the inertia: export the tensor from the builder
 (CadQuery: the solid's matrix of inertia scaled by density) for any part that matters.
 Exit: 0 written, 1 a listed part is missing or has no mass, 2 bad arguments.
=======================================================================================================================
"""
import argparse
import datetime
import json
import math
import os
import sys

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass


def _norm(v):
    """Unit vector; raises on a zero vector."""
    n = math.sqrt(sum(x * x for x in v))
    if not n > 1e-12:
        raise ValueError("axis direction is zero")
    return [x / n for x in v]


def link_properties(parts, names, axis_point_mm, axis_dir):
    """
    (mass_kg, l_com_m, j_axis_kgm2, point_mass_parts) for the named parts about the axis through axis_point_mm along
    axis_dir. Raises ValueError naming the first missing or massless part.
    """
    n = _norm(axis_dir)
    m_tot, mx = 0.0, [0.0, 0.0, 0.0]
    j, point_mass = 0.0, []
    for name in names:
        row = parts.get(name)
        if not isinstance(row, dict) or not isinstance(row.get("mass_g"), (int, float)) or not row["mass_g"] > 0:
            raise ValueError(f"part {name!r} missing or without a positive mass_g")
        com = row.get("com_mm")
        if not (isinstance(com, list) and len(com) == 3 and all(isinstance(c, (int, float)) for c in com)):
            raise ValueError(f"part {name!r} has no 3-number com_mm")
        m = row["mass_g"] / 1000.0
        r = [(com[i] - axis_point_mm[i]) / 1000.0 for i in range(3)]          # m, from the axis point
        along = sum(r[i] * n[i] for i in range(3))
        perp = [r[i] - along * n[i] for i in range(3)]
        d2 = sum(p * p for p in perp)
        # ---- the part's own inertia about its CoM, projected on the axis: n^T I n (kg mm^2 -> kg m^2)
        own = 0.0
        tensor = row.get("inertia_kgmm2")
        if isinstance(tensor, list) and len(tensor) == 3 and all(isinstance(r3, list) and len(r3) == 3 for r3 in tensor):
            own = sum(n[i] * tensor[i][k] * n[k] for i in range(3) for k in range(3)) * 1e-6
        else:
            point_mass.append(name)
        j += own + m * d2
        m_tot += m
        for i in range(3):
            mx[i] += m * perp[i]
    com_perp = [x / m_tot for x in mx]
    return m_tot, math.sqrt(sum(c * c for c in com_perp)), j, point_mass


def write_params(path, src, names, props):
    """Write the include file with its provenance header."""
    m, l, j, pm = props
    lines = [
        "# GENERATED by sim/twin/tools/cad_to_twin.py; do not edit by hand (rerun it after every CAD change)",
        f"# source: {src}  parts: {' '.join(names)}  date: {datetime.date.today().isoformat()}",
    ]
    if pm:
        lines.append(f"# WARNING point masses (no inertia_kgmm2 exported, inertia underestimated): {' '.join(pm)}")
    lines += [f"joint.m_link_kg = {m:.9g}", f"joint.l_com_m = {l:.9g}", f"joint.j_link_kgm2 = {j:.9g}", ""]
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


def self_test():
    """Closed-form checks: a point mass on an arm, a rod with its own inertia, the axis offset."""
    passed = failed = 0

    def chk(ok, what):
        nonlocal passed, failed
        passed, failed = (passed + 1, failed) if ok else (passed, failed + 1)
        if not ok:
            print(f"FAIL {what}")

    # ---- 0.3 kg point mass 150 mm out along X, axis along Y through the origin: J = m l^2
    parts = {"arm": {"mass_g": 300.0, "com_mm": [150.0, 0.0, 0.0]}}
    m, l, j, pm = link_properties(parts, ["arm"], [0, 0, 0], [0, 1, 0])
    chk(abs(m - 0.3) < 1e-12 and abs(l - 0.15) < 1e-12 and abs(j - 0.3 * 0.15 ** 2) < 1e-12, "point mass")
    chk(pm == ["arm"], "point mass reported")

    # ---- uniform rod 300 mm along X from the axis: own inertia m L^2 / 12 about its centre, total m L^2 / 3
    i_c = 0.3 * 300.0 ** 2 / 12.0
    parts = {"rod": {"mass_g": 300.0, "com_mm": [150.0, 0.0, 0.0],
                     "inertia_kgmm2": [[0.0, 0.0, 0.0], [0.0, i_c, 0.0], [0.0, 0.0, i_c]]}}
    m, l, j, pm = link_properties(parts, ["rod"], [0, 0, 0], [0, 1, 0])
    chk(abs(j - 0.3 * 0.3 ** 2 / 3.0) < 1e-12 and not pm, "rod about its end")

    # ---- the along-axis offset does not count; the axis point does
    parts = {"a": {"mass_g": 100.0, "com_mm": [10.0, 500.0, 0.0]}}
    m, l, j, _ = link_properties(parts, ["a"], [0, 0, 0], [0, 1, 0])
    chk(abs(l - 0.01) < 1e-12, "along-axis offset ignored")
    m, l, j, _ = link_properties(parts, ["a"], [10.0, 0, 0], [0, 1, 0])
    chk(abs(l) < 1e-12 and abs(j) < 1e-15, "axis through the CoM")

    # ---- refusals
    try:
        link_properties({"x": {"mass_g": 0, "com_mm": [0, 0, 0]}}, ["x"], [0, 0, 0], [0, 1, 0])
        chk(False, "massless part refused")
    except ValueError:
        chk(True, "massless part refused")
    total = passed + failed
    print(f"[hil] cad_to_twin: {passed}/{total} checks passed, {failed} failed")
    return 0 if failed == 0 else 1


def main():
    ap = argparse.ArgumentParser(description="CAD export -> twin link mass properties")
    ap.add_argument("--parts", help="cad/<asm>/parts.json")
    ap.add_argument("--link", nargs="+", help="the part names that move with the joint")
    ap.add_argument("--axis-mm", nargs=3, type=float, help="a point on the joint axis, CAD frame, mm")
    ap.add_argument("--axis-dir", nargs=3, type=float, help="the joint axis direction, CAD frame")
    ap.add_argument("--out", help="params include file to write")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    if not (a.parts and a.link and a.axis_mm and a.axis_dir and a.out):
        ap.print_usage()
        return 2
    try:
        with open(a.parts, "r", encoding="utf-8") as fh:
            data = json.load(fh)
        props = link_properties(data.get("parts", {}), a.link, a.axis_mm, a.axis_dir)
    except (OSError, ValueError) as exc:
        print(f"[cad_to_twin] {exc}")
        return 1
    write_params(a.out, a.parts.replace("\\", "/"), a.link, props)
    m, l, j, pm = props
    print(f"[cad_to_twin] {a.out}: m {m:.6g} kg, l_com {l:.6g} m, J {j:.6g} kg m^2"
          f"{' (point masses: ' + ', '.join(pm) + ')' if pm else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

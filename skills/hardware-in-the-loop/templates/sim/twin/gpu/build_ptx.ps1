<#
=======================================================================================================================
  build_ptx.ps1 - regenerates gpu\thermal_sweep_ptx.inc from gpu\thermal_sweep.cu. Run it after editing the kernel
                  or thermal_sweep_kernel.h, and commit the .inc with the change (the twin build never runs nvcc).

  Interpreter: PowerShell 7 (pwsh). Run: pwsh -File sim\twin\gpu\build_ptx.ps1 [-Nvcc <path to nvcc>]
  Needs the CUDA toolkit (12.x or newer) and its host compiler (MSVC on Windows: run from a Developer PowerShell,
  or let -allow-unsupported-compiler try clang-cl). Options and why:
    -arch=compute_75        a VIRTUAL architecture: the driver JIT-compiles the PTX for the installed GPU (Turing on)
    -fmad=false             no fused multiply-add: the same rounding as the CPU build (-ffp-contract=off)
    -prec-div / -prec-sqrt  IEEE division and square root, as the CPU does
    -ftz=false              keep denormals, as the CPU does
=======================================================================================================================
#>
param([string]$Nvcc = '')
$ErrorActionPreference = 'Stop'
if (-not $Nvcc) {
  $c = Get-Command nvcc -ErrorAction SilentlyContinue
  if ($c) { $Nvcc = $c.Source }
  elseif ($env:CUDA_PATH) { $Nvcc = Join-Path $env:CUDA_PATH 'bin\nvcc.exe' }
}
if (-not $Nvcc -or -not (Test-Path $Nvcc)) { Write-Output 'build_ptx: nvcc not found (install the CUDA toolkit or pass -Nvcc)'; exit 2 }
$cu = Join-Path $PSScriptRoot 'thermal_sweep.cu'
$ptx = Join-Path $PSScriptRoot 'thermal_sweep.ptx'
$inc = Join-Path $PSScriptRoot 'thermal_sweep_ptx.inc'
& $Nvcc -ptx -arch=compute_75 -O2 -fmad=false -prec-div=true -prec-sqrt=true -ftz=false -o $ptx $cu
if ($LASTEXITCODE -ne 0) { Write-Output "build_ptx: nvcc failed ($LASTEXITCODE)"; exit 1 }

# ---- embed: one C string literal per PTX line (quotes and backslashes escaped), NUL-terminated by the compiler
$lines = Get-Content $ptx -Encoding utf8
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('/* GENERATED by sim/twin/gpu/build_ptx.ps1 from thermal_sweep.cu - do not edit; regenerate. */')
[void]$sb.AppendLine('static const char tw_thermal_sweep_ptx[] =')
foreach ($l in $lines) {
  $e = $l.Replace('\', '\\').Replace('"', '\"')
  [void]$sb.AppendLine('    "' + $e + '\n"')
}
[void]$sb.AppendLine('    ;')
[System.IO.File]::WriteAllText($inc, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))
Remove-Item $ptx
Write-Output "build_ptx: wrote $inc ($($lines.Count) PTX lines)"
